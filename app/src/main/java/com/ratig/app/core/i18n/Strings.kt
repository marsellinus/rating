/** The string catalog for one language, with Indonesian fallback for any gap. */
class Loc(private val language: AppLanguage) {
    fun t(key: S): String = when (language) {
        AppLanguage.ID -> ID[key]
        AppLanguage.EN -> EN[key] ?: ID[key]
    } ?: key.name
}

/** Current language + strings, provided at the top of the Compose tree. */
val LocalAppLanguage = staticCompositionLocalOf { AppLanguage.ID }
val LocalStrings = staticCompositionLocalOf { Loc(AppLanguage.ID) }
